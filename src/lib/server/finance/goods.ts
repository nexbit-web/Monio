/**
 * Встроенный словарь товаров — сами слова в goods.json: «яблоки» → Продукты,
 * «носки» → Одежда, «порошок» → Дом и быт. По-русски и по-украински.
 * Работает сразу для всех, без правок в базе, и не засоряет слова-подсказки
 * категорий в CRM. Как записывать слова — в начале goods.json («_как_писать»).
 *
 * Категорию пользователя для группы находим по значку (icons), а если значок
 * свой — по началу названия (names): переименование категории словарь не ломает.
 * Слова, которые пользователь сам закрепил за категорией, важнее словаря
 * (см. categorize.ts) — так бот учится на исправлениях.
 */
import type { IconKey } from '../../icon-keys.ts';
import data from './goods.json' with { type: 'json' };

export type GoodsGroup = {
	/** значки категорий этой группы (старые эмодзи переводит iconKey) */
	icons: IconKey[];
	/** слова «кому» (Семья, Благотворительность) важнее товара: «сестре куртка» → Семья */
	priority?: boolean;
	/** начала слов в названии категории — если значок у категории свой */
	names: string[];
	/** основы слов; «=слово» — только целиком, «+слово» — сильное */
	words: string[];
};

/** Группы словаря без служебных полей («_как_писать»). */
export const GOODS = Object.fromEntries(
	Object.entries(data).filter(([key]) => !key.startsWith('_'))
) as unknown as Record<string, GoodsGroup>;
